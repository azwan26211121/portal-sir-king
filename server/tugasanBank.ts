function makeQ(
  prefix: string,
  idx: number,
  prompt: string,
  maxMarks: number,
  rubricHint: string,
  subPrompts?: string[]
): TugasanQuestion {
  return {
    id: `${prefix}-q${idx}`,
    numberLabel: `${idx}.`,
    prompt,
    ...(subPrompts && subPrompts.length > 0 ? { subPrompts } : {}),
    maxMarks,
    rubricHint,
  };
}

