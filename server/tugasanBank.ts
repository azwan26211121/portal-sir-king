export function createDefaultTugasanForCustomCu(level: TopicLevel, cu: CUModule): TugasanPaper {
  const cleanCode = cu.code.trim() || 'CU';
  const cleanTitle = cu.title.trim() || 'Unit Kompetensi Baharu';
  const paperId = `tug-${cu.id}-1`;
  const tahapNum = level.code.replace(/[^0-9]/g, '') || level.code;
  return {
    id: paperId,
    cuId: cu.id,
    setCode: 'T(1/1)',
    programCodeTitle: `${level.code} — ${level.title}`.toUpperCase(),
    tahap: tahapNum,
    cuCodeTitle: `${cleanCode} ${cleanTitle}`.toUpperCase(),
    workActivities: [
      `1. PREPARE ${cleanTitle.toUpperCase()} REQUIREMENTS.`,
      `2. PERFORM ${cleanTitle.toUpperCase()} PROCEDURES.`,
      `3. VERIFY SAFETY AND QUALITY COMPLIANCE.`,
    ],
    paperCode: `${level.code}-${cleanCode}/T(1/1)`,
    title: cleanTitle.toUpperCase(),
    purpose: `Kertas Tugasan ini bertujuan menilai kefahaman dan pengetahuan pelatih tentang ${cleanTitle} mengikut piawaian keselamatan dan peraturan elektrik berkaitan.`,
    instructions: DEFAULT_INSTRUCTIONS,
    passingScore: 60,
    questions: [
      makeQ(
        paperId,
        1,
        `Nyatakan tujuan utama dan skop kerja bagi unit kompetensi ${cleanCode}: ${cleanTitle}.`,
        5,
        `Menjelaskan objektif teknikal, komponen utama serta pematuhan piawaian kerja bagi ${cleanTitle}.`
      ),
      makeQ(
        paperId,
        2,
        `Senaraikan tiga (3) langkah keselamatan (PPE / LOTO / Pengasingan) yang wajib dipatuhi sebelum memulakan kerja ${cleanTitle}.`,
        5,
        'Pemakaian PPE lengkap, pengasingan bekalan & LOTO, pengesahan litar mati dan pemeriksaan alat uji.'
      ),
      makeQ(
        paperId,
        3,
        `Terangkan prosedur pengujian atau pemeriksaan kualiti selepas kerja ${cleanTitle} selesai dilaksanakan.`,
        5,
        'Pemeriksaan visual, ujian keterusan/penebatan/kefungsian mengikut MS IEC 60364 dan perekodan laporan.'
      ),
    ],
    references: [
      'Jabatan Pembangunan Kemahiran (JPK) — Panduan Penilaian Pengetahuan NOSS.',
      'MS IEC 60364 & Peraturan-Peraturan Elektrik 1994 (Suruhanjaya Tenaga).',
    ],
    updatedAt: new Date().toISOString(),
  };
}
